        "\n",
        "# --------------------------------------------------\n",
        "# 10. MONTHLY ELECTRICITY PROFILE\n",
        "# --------------------------------------------------\n",
        "st.header(\"2. Monthly Electricity Consumption\")\n",
        "\n",
        "fig_monthly = px.bar(\n",
        "    monthly,\n",
